test("About tells the whole story, in a dialog that closes with Escape and returns focus", async ({ page }) => {
  await page.goto("/");
  const open = page.getByRole("button", { name: /About/ });
  await open.click();
  const dlg = page.getByRole("dialog", { name: "About Anubhav" });
  await expect(dlg).toBeVisible();
  for (const text of ["The problem", "What Anubhav does", "Built on Meta Muse", "Muse Spark Open", "Muse Spark 1.3", "Muse Voice Transcribe",
    "1 to 1.5 hours", "12.5 million trucks", "Synthetic data. Every company, person, site, truck and record here is generated by the project's own code",
    "Meta Global AI Developer Hackathon", "recorded earlier on Muse Spark Open", "has not been measured yet"]) {
    await expect(dlg).toContainText(text);
  }
  await expect(dlg.getByRole("link", { name: /Redseer/ })).toHaveAttribute("href", /redseer\.com/);
  await page.keyboard.press("Escape");
  await expect(dlg).toBeHidden();
  await expect(open).toBeFocused();
});

test("About closes with its button, and passes the contrast check in both themes", async ({ page }) => {
  for (const scheme of ["light", "dark"] as const) {
    await page.emulateMedia({ colorScheme: scheme, reducedMotion: "reduce" });
    await page.goto("/");
    await page.getByRole("button", { name: /About/ }).click();
    const res = await new AxeBuilder({ page }).include("dialog").withTags(["wcag2aa"]).analyze();
    expect(res.violations.map((v) => `${v.id}: ${v.nodes.map((n) => n.target).join(" | ")}`)).toEqual([]);
    await page.getByRole("button", { name: "Close" }).click();
    await expect(page.getByRole("dialog")).toBeHidden();
  }
});

