import { useEffect, useRef } from "react";
import { X } from "lucide-react";

/** The full story: the problem, what Anubhav does, which Meta models it uses, and what is and is not real in this demo. */
export function About({ open, onClose }: { open: boolean; onClose: () => void }) {
  const ref = useRef<HTMLDialogElement>(null);

  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (open && !d.open) d.showModal(); // a native modal: focus is trapped and Esc closes it
    if (!open && d.open) d.close();
  }, [open]);

  return (
    <dialog ref={ref} className="about-dialog" aria-labelledby="about-title" onClose={onClose}>
      <header className="about-head">
        <h2 id="about-title">About Anubhav</h2>
        <button type="button" className="theme" aria-label="Close" onClick={onClose}><X size={18} aria-hidden /></button>
      </header>

      <section>
        <h3>The problem</h3>
        <p>
          Every business has rules nobody wrote down. A dispatcher near Warangal knows that a 32 ft truck cannot get into one Jangaon
          godown. That rule is in no system, so an AI agent connected to the company's data passes every check and still sends the truck.
        </p>
        <p>
          In an interview with a former FMCG logistics manager, one transport plan took 1 to 1.5 hours, with up to 10 re-plans in festival
          season, and the constraints lived in the planner's head (one interview, anonymised).
        </p>
        <p className="small muted">
          India has about 12.5 million trucks run by about 3.5 million operators, and around 75% of operators own fewer than five trucks
          (<a href="https://redseer.com/articles/unlocking-growth-in-indias-fragmented-trucking-sector/" target="_blank" rel="noreferrer">Redseer, Dec 2024</a>).
          Small operators run on phone calls, notes and memory. Logistics costs India about 7.97% of GDP
          (<a href="https://aslindia.net/newsletters/indias-logistics-costs-fall-to-797-of-gdp-in-fy-202324-dpiit" target="_blank" rel="noreferrer">DPIIT–NCAER, 2023–24</a>).
        </p>
      </section>

      <section>
        <h3>What Anubhav does</h3>
        <ol>
          <li>A dispatcher asks in Telugu, Roman Telugu or English, by text or voice.</li>
          <li>The agent plans a <strong>draft</strong> trip with generic tools over the company's data. It never dispatches.</li>
          <li>Meta Muse reads the company's trip history and proposes rules nobody wrote down.</li>
          <li>Code checks the evidence, a person approves each rule, and the next plan uses it.</li>
          <li>Approved regional knowledge can be shared with a new company, so it starts smarter on day 1, without leaking anything private.</li>
        </ol>
        <p className="small muted">"Anubhav" means "experience".</p>
      </section>

      <section>
        <h3>Built on Meta Muse</h3>
        <div className="tablewrap">
          <table>
            <thead><tr><th>Model</th><th>Role</th></tr></thead>
            <tbody>
              <tr><td><strong>Muse Spark Open</strong></td><td>The agent: plans, calls tools, answers in the user's language. Open weights.</td></tr>
              <tr><td><strong>Muse Spark 1.3</strong></td><td>Reads trip history offline and proposes candidate rules. Code checks everything it proposes.</td></tr>
              <tr><td><strong>Muse Voice Transcribe</strong></td><td>Turns Telugu and Roman Telugu speech into text.</td></tr>
            </tbody>
          </table>
        </div>
      </section>

      <section>
        <h3>What is real in this demo</h3>
        <ul>
          <li><strong>Synthetic data.</strong> Every company, person, site, truck and record here is generated by the project's own code. No real company's data was used.</li>
          <li><strong>Replay mode.</strong> With no model keys here, answers replay runs recorded earlier on Muse Spark Open, each labelled with its date and model. A run labelled "Scripted" comes from a test model, not a real one.</li>
          <li><strong>Benchmarks.</strong> The Proof tab shows measured results: learning unwritten rules, a new company on day 1, learned tools, rule mining, and the team of agents against one Planner. Whether each agent improves version by version has not been measured yet.</li>
        </ul>
      </section>

      <p className="small muted">Built for the Meta Global AI Developer Hackathon, Indie track, theme Push the Frontier.</p>
    </dialog>
  );
}
