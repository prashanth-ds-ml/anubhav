import { api, type ProofEntry } from "../lib/api";
import { useApi } from "../lib/useApi";
import { useFocusTarget } from "../lib/focus";

const REPO = "https://github.com/prashanth-ds-ml/anubhav/blob/main/";

function Tile({ id, before, after, label, what, href }: { id: string; before?: string; after: string; label: string; what: string; href: string }) {
  const ref = useFocusTarget<HTMLElement>(id, true);
  return (
    <article ref={ref} className="tile" aria-label={label}>
      <p className="tile-num">{before && <><span className="tile-before">{before}</span> <span aria-hidden>→</span><span className="sr-only">to</span> </>}<strong>{after}</strong></p>
      <p className="tile-label">{label}</p>
      <p className="small muted">{what} <a href={href} target="_blank" rel="noreferrer">Result file</a></p>
    </article>
  );
}

function Headline({ e }: { e: ProofEntry }) {
  const p = e.pooled!, reps = e.repeats ?? [];
  const file = `${REPO}artifacts/benchmark/exp011r_20261030_230811.json`;
  return (
    <section aria-label="Headline results" className="tiles">
      <Tile id="proof:rules" before={pct(p.raw_notes_B)} after={pct(p.lessons_C)} label="Unwritten rules handled"
        what={`${reps[0]?.n_unwritten ?? "?"} cases a repeat, 3 repeats, without and with approved lessons.`} href={file} />
      <Tile id="proof:transfer" before={pct(p.cold_B)} after={pct(p.pack_E)} label="New company, day 1"
        what={`${reps[0]?.n_transfer ?? "?"} cases a repeat, with regional lessons shared from other companies.`} href={file} />
      <Tile id="proof:safe" after={String(p.C_unsafe)} label="Unsafe plans with lessons"
        what="Checked by code on every draft; 0 private details leaked across companies." href={file} />
    </section>
  );
}

const pct = (x: number | undefined | null) => (typeof x === "number" ? `${Math.round(x * 100)}%` : "n/a");

function Learning({ e }: { e: ProofEntry }) {
  const p = e.pooled!, reps = e.repeats ?? [];
  return (
    <section aria-labelledby="p-learn">
      <h3 id="p-learn">Does it learn rules nobody wrote down?</h3>
      <p className="small muted">Muse Spark Open, {e.measured_on}. Cases were generated by the project's own code.</p>
      <div className="tablewrap">
        <table className="fit">
          <caption className="small muted">Share of cases answered correctly. Unwritten rules means gate limits, nicknames and real truck capacity. On day 1 a new company uses regional rules shared from other companies.</caption>
          <thead><tr><th>Question</th><th>Without lessons</th><th>With approved lessons</th><th>Cases per repeat</th></tr></thead>
          <tbody>
            <tr><td>Unwritten rules</td><td>{pct(p.raw_notes_B)}</td><td><strong>{pct(p.lessons_C)}</strong></td><td>{reps[0]?.n_unwritten}</td></tr>
            <tr><td>New company, day 1</td><td>{pct(p.cold_B)}</td><td><strong>{pct(p.pack_E)}</strong></td><td>{reps[0]?.n_transfer}</td></tr>
          </tbody>
        </table>
      </div>
      <ul className="plain">
        <li>Unsafe drafts with lessons: <strong>{p.C_unsafe}</strong>. The leak check found 0 private details in the shared packs.</li>
        <li>Replicated in {e.replicated?.lessons ? "3 of 3" : "not all"} repeats for lessons and {e.replicated?.transfer ? "3 of 3" : "not all"} for sharing, against bars fixed in advance.</li>
        <li>Gain per repeat on unwritten rules: {reps.map((r) => `+${Math.round(r.lessons_gain_pts)}`).join(", ")} points.</li>
      </ul>
      <p className="small"><strong>Not improved:</strong> real truck capacity. With lessons it scored 0/6; the agent refuses to overload a truck but does not finish a safe plan.</p>
    </section>
  );
}

function Team({ e }: { e: ProofEntry }) {
  const d = e.decision!;
  const rows: [string, any][] = [["Single Planner", d.S], ["Team", d.M0], ["Team after one learning round", d.M1]];
  return (
    <section aria-labelledby="p-team">
      <h3 id="p-team">Team of agents against one Planner</h3>
      <p className="small muted">54 cases, one repeat, Muse Spark Open.</p>
      <div className="tablewrap">
        <table className="fit">
          <caption className="small muted">Correct cases, unsafe drafts, and cost per case.</caption>
          <thead><tr><th>Arm</th><th>Correct</th><th>Unsafe</th><th>Cost a case</th><th>Right agent chosen</th></tr></thead>
          <tbody>{rows.map(([n, r]) => (
            <tr key={n}><td>{n}</td><td>{r.ok}/{r.n}</td><td>{r.unsafe}</td><td>${r.mean_cost.toFixed(3)}</td><td>{r.handoffs === 0 && n === "Single Planner" ? "n/a" : pct(r.routing)}</td></tr>
          ))}</tbody>
        </table>
      </div>
      <p className="small"><strong>The team is not more accurate or cheaper than one planner.</strong> It was within the bars set in advance (no unsafe drafts, within 5 points, within 1.5× the cost). What it adds is visible hand-offs, new tools and per-agent learning. The learning round did not improve answers.</p>
    </section>
  );
}

function Tools({ e }: { e: ProofEntry }) {
  const a = e.arms!;
  const calls = 1 - a.T.mean_tool_calls / a.Q.mean_tool_calls;
  return (
    <section aria-labelledby="p-tools">
      <h3 id="p-tools">Do repeated questions become cheaper tools?</h3>
      <p className="small muted">16 held-out questions. {e.measured_on}.</p>
      <ul className="plain">
        <li>The learned tool was used in {e.decision?.learned_tool_used_in} runs.</li>
        <li>Tool calls fell {Math.round(calls * 100)}% ({a.Q.mean_tool_calls} to {a.T.mean_tool_calls} a question) and cost fell {Math.round((1 - a.T.mean_cost / a.Q.mean_cost) * 100)}%.</li>
        <li><strong>The bar was not met:</strong> the pre-registered goal was 30% fewer calls, and answers were not worse ({pct(a.T.answer_ok)} against {pct(a.Q.answer_ok)}).</li>
      </ul>
    </section>
  );
}

function Mining({ e }: { e: ProofEntry }) {
  const p = e.pooled!;
  return (
    <section aria-labelledby="p-mine">
      <h3 id="p-mine">How good are the proposed rules?</h3>
      <p className="small muted">Offline lesson mining by Muse Spark 1.3, compared with the rules the data generator hid.</p>
      <ul className="plain">
        <li>Precision {pct(p.precision)}: of {p.passed} rules that passed the checks, {p.true_passed} were real.</li>
        <li>Recall {pct(p.recall)}: found {p.found} of {p.learnable} learnable rules.</li>
        <li>Trap rules admitted: <strong>{(p.traps_admitted ?? []).length}</strong>. These are plausible rules the data does not support.</li>
      </ul>
    </section>
  );
}

export function Proof() {
  const { data, loading } = useApi(api.proof);
  if (loading) return <div className="skeleton" aria-busy="true" />;
  const by = (id: string) => data!.find((x) => x.id === id);
  const learning = by("EXP-011R"), team = by("EXP-013"), tools = by("EXP-012b"), mining = by("EXP-009b");
  if (!learning && !team && !tools && !mining) return <p className="empty">No results to show. The server may be unreachable.</p>;
  return (
    <div>
      {learning?.pooled && <Headline e={learning} />}
      <p className="small muted">Measured on Muse Spark Open with cases generated by the project's own code. Details and what did not improve are below.</p>
      {learning?.pooled && <Learning e={learning} />}
      {team?.decision && <Team e={team} />}
      {tools?.arms && <Tools e={tools} />}
      {mining?.pooled && <Mining e={mining} />}
      <section aria-labelledby="p-open">
        <h3 id="p-open">Not measured yet</h3>
        <ul className="plain">
          <li>Whether each agent, and the whole team, improves version by version. That curve has not been run.</li>
          <li>Results on Muse Spark 1.3 as the planner: every measured planning run used Muse Spark Open.</li>
        </ul>
      </section>
      <p className="small muted">Every case was generated by the project's own code on synthetic companies. Numbers come from the committed result files.</p>
    </div>
  );
}
