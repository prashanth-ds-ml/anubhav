import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" })).newPage();
await p.goto("http://localhost:7860/");
await p.locator(".starter").first().waitFor({ timeout: 30000 });
await p.screenshot({ path: `${out}_first.png` });
await p.getByRole("button", { name: /About/ }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}_about.png` });
await p.keyboard.press("Escape");
await p.goto("http://localhost:7860/#proof");
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}_proof.png` });
await b.close();
